const { chromium } = require('playwright');

(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 375, height: 812 } });
  await page.goto('http://localhost:8080/interactive_pages/scheda-esame.html');
  const btn = page.locator('button:has-text("قبول ومتابعة")');
  if (await btn.isVisible()) {
    await btn.click();
    await page.waitForTimeout(300);
  }
  await page.evaluate(() => {
    document.documentElement.classList.remove('light');
    localStorage.setItem('patente_theme', 'dark');
  });
  await page.waitForTimeout(200);
  await page.screenshot({ path: 'C:/Users/Ramy Fahmy/.gemini/antigravity/brain/e7065af7-148e-49c5-9b06-fabf7a80a8e1/verified_exam_dark_clean.png' });
  await browser.close();
  console.log('Saved clean dark mode screenshot');
})();
